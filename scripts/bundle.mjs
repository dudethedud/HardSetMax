// Builds the deploy/ folder that the `deploy` branch carries (docs/OPERATIONS.md):
// the whole bot in one file, the migration files, and a tiny start.js. The host
// then runs it without `npm install` or a build, which the free server's CPU
// limit can't take. Run by .github/workflows/deploy.yml; `npm run bundle` locally.
import { build } from 'esbuild';
import { cpSync, existsSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const out = 'deploy';
const pkg = JSON.parse(readFileSync('package.json', 'utf8'));
rmSync(out, { recursive: true, force: true });
mkdirSync(out);

await build({
  entryPoints: ['src/deploy.ts'],
  outfile: join(out, 'bot.mjs'),
  bundle: true,
  platform: 'node',
  target: 'node22',
  format: 'esm',
  // Optional native speed-ups discord.js and pg look for; they're never installed.
  external: ['zlib-sync', 'bufferutil', 'utf-8-validate', 'pg-native'],
  // Some bundled packages still call require(); give the ESM bundle one.
  banner: { js: "import { createRequire as __createRequire } from 'node:module'; const require = __createRequire(import.meta.url);" },
  define: { __BOT_VERSION__: JSON.stringify(pkg.version) },
  legalComments: 'none',
  logLevel: 'warning',
});

// The host runs start.js. With no package.json next to it, .js is CommonJS, so it
// loads the ESM bundle with import().
writeFileSync(
  join(out, 'start.js'),
  "// Generated by scripts/bundle.mjs. Runs migrations, then the bot.\nimport('./bot.mjs').catch((err) => {\n  console.error(err);\n  process.exit(1);\n});\n",
);

for (const name of readdirSync('prisma/migrations')) {
  const file = join('prisma/migrations', name, 'migration.sql');
  if (existsSync(file)) cpSync(file, join(out, 'migrations', name, 'migration.sql'));
}

writeFileSync(
  join(out, 'README.md'),
  `# Colour menu bot: deploy build\n\nGenerated from \`main\` by GitHub Actions (version ${pkg.version}). Don't edit this branch: change \`main\`.\nThe host runs \`node start.js\` with no \`npm install\`. Setup: docs/OPERATIONS.md on \`main\`.\n`,
);
console.log(`deploy/ ready: bot.mjs, start.js, ${readdirSync(join(out, 'migrations')).length} migrations`);
